"""spec 2 -> 3: drop the per-stock-kind aliquot tables, recreate the views.

Spec 3 (0.2.0, ticket 23) settles git-bug ``2f6a0d5`` by making the model
explicit: an **aliquot is a generic tube** (location, quantity, unit, status,
label, notes) and every property of the material belongs on the **stock kind**.
The generated shape therefore changes twice:

* the ``aliquot_<stockkind>`` extension tables disappear (``aliquot_fields``
  was removed from the schema language; such a preset no longer loads);
* every ``v_stock_<kind>`` gains ``entity_kind``/``entity_name``,
  ``aliquots_stored``/``aliquots_total``, ``quantity_stored``/``unit`` and the
  derived ``status`` before its final ``alias_list``.

The step refuses when an extension table still **holds a value** (:func:`plan`
lists the offending ``table.column`` and its values): those properties have to
move to the stock kind first, with a preset/local step like molbio 1-to-2's
``glycerol_pct`` move, and the old table then has to be dropped by that step.
Empty or all-NULL extension tables lose nothing and are dropped here.

Views are recreated from the ledger's own (now spec-3) schema and the derived
``dolt_tests`` are regenerated from it — they were generated by the spec-2 tool
and may still name ``aliquot_<kind>`` tables.  Both happen in the one
``migrate(ledger): spec 2 -> 3`` commit through the shared runner: the step
declares ``schema=``, so the runner writes that schema's fingerprint and
reinstalls the generated tests in the same commit.

Run it by hand::

    uv run migration/spec/2-to-3/migrate.py --ledger PATH [--branch B] [--dry-run]

A ledger whose preset still declares ``aliquot_fields`` cannot be opened by
0.2.0+ at all; run the spec-1/spec-2 era steps (presets/molbio/1-to-2 and any
local kind move) with the last checkout that accepted the key, then this step
from the 0.2.0 tree.  See the README.
"""

from __future__ import annotations

from tetramark.core.ledger import Ledger
from tetramark.errors import LedgerError
from tetramark.migrate import MigrationStep, main
from tetramark.schema.ddl import view_statements
from tetramark.schema.model import EffectiveSchema

#: Per-stock-kind extension tables were named ``aliquot_<stockkind>``; the two
#: core tables with the same prefix are not extensions.  The LIKE pattern
#: escapes the ``_`` so ``aliquot_`` is a literal prefix, not a wildcard.
_EXTENSION_LIKE = "aliquot" + r"\_%"
CORE_ALIQUOT_TABLES = frozenset({"aliquot", "aliquot_event"})


def _extension_tables(ledger: Ledger) -> list[str]:
    """Live ``aliquot_<stockkind>`` tables, sorted (extension tables only)."""
    rows = ledger.driver.query(
        "SELECT `table_name` AS `name` FROM `information_schema`.`tables` "
        "WHERE `table_schema` = DATABASE() AND `table_type` = 'BASE TABLE' "
        "AND `table_name` LIKE %s ORDER BY `table_name`",
        (_EXTENSION_LIKE,),
    )
    return [
        str(row["name"])
        for row in rows
        if str(row["name"]) not in CORE_ALIQUOT_TABLES
    ]


def _columns(ledger: Ledger, table: str) -> list[str]:
    """The stored (non-generated) columns of ``table`` except ``id``."""
    rows = ledger.driver.query(
        "SELECT `column_name` AS `name`, `extra` AS `extra` "
        "FROM `information_schema`.`columns` "
        "WHERE `table_schema` = DATABASE() AND `table_name` = %s "
        "ORDER BY `ordinal_position`",
        (table,),
    )
    return [
        str(row["name"])
        for row in rows
        if str(row["name"]) != "id"
        and "GENERATED" not in str(row.get("extra") or "").upper()
    ]


def _values(ledger: Ledger, table: str, column: str) -> list[str]:
    """Up to four distinct non-NULL values of ``table.column`` as text."""
    rows = ledger.driver.query(
        f"SELECT DISTINCT CAST(`{column}` AS CHAR) AS `v` FROM `{table}` "
        f"WHERE `{column}` IS NOT NULL ORDER BY `v` LIMIT 4"
    )
    return [str(row["v"]) for row in rows]


def populated_extension_columns(ledger: Ledger) -> dict[str, dict[str, list[str]]]:
    """``table`` → ``column`` → non-NULL values of every populated extension.

    An empty extension table, or one whose every property column is NULL, has
    nothing to lose and is dropped.  A table with a value is a different
    material property recorded per tube, which spec 3 cannot store: the step
    must refuse and name it (spec 3 decisions, ticket 23).
    """
    found: dict[str, dict[str, list[str]]] = {}
    for table in _extension_tables(ledger):
        for column in _columns(ledger, table):
            values = _values(ledger, table, column)
            if values:
                found.setdefault(table, {})[column] = values
    return found


def _describe(found: dict[str, dict[str, list[str]]]) -> str:
    lines = []
    for table in sorted(found):
        for column in sorted(found[table]):
            shown = ", ".join(found[table][column])
            lines.append(f"  {table}.{column}: {shown}")
    return "\n".join(lines)


def plan(ledger: Ledger) -> list[str]:
    """Refuse on a populated extension, else drop the empty ones and rebuild views."""
    populated = populated_extension_columns(ledger)
    if populated:
        raise LedgerError(
            "refusing to migrate spec 2 -> 3: these aliquot extension tables "
            "still hold values, but spec 3 has no per-stock-kind aliquot "
            "tables:\n"
            + _describe(populated)
            + "\nMove those properties to the stock kind first (like molbio "
            "1-to-2 moves glycerol_pct onto stock_bacterial_glycerol), with a "
            "preset/local migration step that copies the values and drops the "
            "old table, then retry. Nothing was written."
        )

    statements = [
        f"DROP TABLE IF EXISTS `{table}`" for table in _extension_tables(ledger)
    ]
    # Every generated view is recreated from the ledger's own schema, which is
    # now spec-3 shaped: a stock view gains the entity/aliquot/quantity/status
    # columns and no view refers to an extension table.  All drops run before
    # all creates so a view that depended on another would still be valid.
    views = view_statements(ledger.schema)
    statements.extend(f"DROP VIEW IF EXISTS `{statement.name}`" for statement in views)
    statements.extend(statement.sql for statement in views)
    return statements


def target_schema(ledger: Ledger) -> EffectiveSchema:
    """The spec-3 schema the ledger opens with (the YAML itself unchanged).

    A spec step does not change the preset files; only the generated shape
    (drop extension tables, spec-3 views/tests) and the counter move.  The
    runner writes this schema's fingerprint and regenerates ``dolt_tests``
    from it in the migration commit.
    """
    return ledger.schema


step = MigrationStep(
    kind="spec",
    from_version=2,
    plan=plan,
    schema=target_schema,
    description=(
        "drop the empty aliquot_<stockkind> extension tables, recreate the "
        "generated views with the stock entity/aliquot/quantity/status columns, "
        "and regenerate the derived dolt_tests"
    ),
)


if __name__ == "__main__":
    main(step)
